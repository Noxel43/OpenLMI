fn glyph(c: char) -> &'static [u8; 5] {
    let i = c as usize;
    if (0x20..0x7f).contains(&i) {
        &FONT[i - 0x20]
    } else {
        &FONT[('?' as usize) - 0x20]
    }
}

/// Whether the pixel at (`col`, `row`) of a line of text is lit. `col` counts
/// from the left edge of the first character.
pub fn pixel(text: &[char], col: i64, row: i64) -> bool {
    if col < 0 || row < 0 || row >= GLYPH_H as i64 {
        return false;
    }
    let (ci, cx) = ((col as usize) / ADVANCE, (col as usize) % ADVANCE);
    if cx >= GLYPH_W || ci >= text.len() {
        return false;
    }
    glyph(text[ci])[cx] & (1 << row) != 0
}

pub fn width(text: &[char]) -> usize {
    text.len() * ADVANCE
}

#[cfg(test)]
mod tests {
    use super::*;

    fn render(s: &str) -> Vec<String> {
        let chars: Vec<char> = s.chars().collect();
        (0..GLYPH_H as i64)
            .map(|row| {
                (0..width(&chars) as i64)
                    .map(|col| if pixel(&chars, col, row) { '#' } else { '.' })
                    .collect()
            })
            .collect()
    }

    #[test]
    fn glyphs_look_right() {
        assert_eq!(
            render("Hi"),
            vec![
                "#...#...#...",
                "#...#.......",
                "#...#..##...",
                "#####...#...",
                "#...#...#...",
                "#...#...#...",
                "#...#..###..",
            ]
        );
        assert_eq!(
            render("7"),
            vec!["#####.", "....#.", "...#..", "..#...", ".#....", ".#....", ".#....",]
        );
    }

    #[test]
    fn out_of_range_is_dark() {
        let t: Vec<char> = "A".chars().collect();
        assert!(!pixel(&t, -1, 0));
        assert!(!pixel(&t, 0, 7));
        assert!(!pixel(&t, 6, 0));
        // Unknown characters fall back to a question mark rather than panicking.
        let u: Vec<char> = "é".chars().collect();
        assert!((0..5).any(|c| (0..7).any(|r| pixel(&u, c, r))));
    }
}
